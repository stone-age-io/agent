package edge

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/stone-age-io/agent/internal/platform"
)

// LeafPidName is the file a leaf started from the generated config writes its
// process id to: the `pid_file` line in nats-leaf.conf, beside the conf itself.
// It is how the agent finds a separately supervised leaf to send SIGHUP to.
const LeafPidName = "nats-leaf.pid"

// LeafStoreDirName is the JetStream store_dir, beside the conf. nats-server
// keeps its data in a `jetstream` directory inside whatever store_dir names, so
// the streams themselves end up in <confdir>/jetstream/jetstream.
const LeafStoreDirName = "jetstream"

type leafConfParams struct {
	OperatorJWT   string
	AccountPub    string
	AccountJWT    string
	SysAccountPub string
	SysAccountJWT string
	Domain        string
	HubLeafURL    string

	// Absolute, all three. See leafConf.
	CredsFile string
	StoreDir  string
	PidFile   string
}

// leafConf turns a platform leaf config into the contents of nats-leaf.conf.
//
// THIS IS THE ONE PLACE THAT DECIDES WHAT THE FILE SAYS. `agent -leaf-config`
// writes its output, and the scheduled refresh compares its output byte for
// byte with the file on disk to decide whether anything changed. Two builders
// would disagree about something trivial -- a comment, a path -- and the
// refresh would then rewrite the file and reload the leaf on every run.
//
// confDir is the directory the conf lives in; credsFile is nats.auth.creds_file,
// of which only the base name is used, because WriteLeafConfig puts the creds
// beside the conf.
//
// EVERY PATH IN THE FILE IS ABSOLUTE. nats-server resolves a relative
// `credentials`, `store_dir` or `pid_file` against its own working directory,
// not the config file's, so a relative one points somewhere else the moment the
// leaf runs with a different cwd -- embedded under a service manager, or
// supervised separately. So all three are computed here from confDir, with
// filepath.Abs, when the file is written. The platform applies the same rule to
// `nats export` (its ADR 0001).
func leafConf(lc *platform.LeafConfig, confDir, credsFile string) (string, error) {
	dir, err := filepath.Abs(confDir)
	if err != nil {
		return "", fmt.Errorf("resolve the leaf config directory %s: %w", confDir, err)
	}
	return buildLeafConf(leafConfParams{
		OperatorJWT:   lc.OperatorJWT,
		AccountPub:    lc.AccountPub,
		AccountJWT:    lc.AccountJWT,
		SysAccountPub: lc.SysAccountPub,
		SysAccountJWT: lc.SysAccountJWT,
		Domain:        lc.Domain,
		HubLeafURL:    lc.HubLeafURL,
		CredsFile:     filepath.Join(dir, filepath.Base(credsFile)),
		StoreDir:      filepath.Join(dir, LeafStoreDirName),
		PidFile:       filepath.Join(dir, LeafPidName),
	}), nil
}

func buildLeafConf(p leafConfParams) string {
	var b strings.Builder
	b.WriteString("# Generated by `agent -leaf-config`. Do not edit by hand.\n")
	b.WriteString("# A running agent keeps resolver_preload current (platform.leaf_refresh_interval).\n")
	b.WriteString("# Re-run `agent -leaf-config` and restart the leaf if the operator changes.\n\n")
	fmt.Fprintf(&b, "server_name: %q\n\n", p.Domain)
	// Strings are written with %q throughout. On Windows that doubles every
	// backslash in a path, which the config lexer unescapes inside a
	// double-quoted string; TestBuildLeafConfIsAcceptedByNATSServer reads the
	// paths back through the real parser to hold it to that.
	fmt.Fprintf(&b, "jetstream {\n  domain: %q\n  store_dir: %q\n}\n\n", p.Domain, p.StoreDir)
	fmt.Fprintf(&b, "operator: %q\n\n", p.OperatorJWT)
	b.WriteString("resolver: MEMORY\n")

	// Two entries, both mandatory.
	//
	// The org account is what this edge actually uses. The system account is
	// named inside the operator JWT, and nats-server resolves it while
	// constructing the server — with resolver: MEMORY there is nowhere else to
	// fetch it from, so preloading only the org account fails outright with
	// "error resolving system account: account missing", before JetStream is
	// even reached. pb-nats preloads it into the hub's config for the same
	// reason (see its generateOperatorConf).
	//
	// This preloads the system account's JWT, which is public trust material
	// like the operator and org account JWTs already here. It does NOT give the
	// edge a $SYS identity: connecting as the system account needs a $SYS *user*
	// credential, which is never served to a leaf node. "No local $SYS" still
	// holds — monitoring is the localhost HTTP port below, not a $SYS user.
	//
	// The org account's JWT is also where NATS user revocations live: pb-nats
	// re-signs it with the revocation list. That is why the agent re-reads it on
	// a timer and reloads the leaf when it moves — see refresh.go.
	b.WriteString("resolver_preload: {\n")
	fmt.Fprintf(&b, "  %s: %q\n", p.AccountPub, p.AccountJWT)
	fmt.Fprintf(&b, "  %s: %q\n", p.SysAccountPub, p.SysAccountJWT)
	b.WriteString("}\n\n")

	// `account` is required on every remote in operator mode — nats-server
	// rejects the config without it ("operator mode requires account nkeys in
	// remotes"). It names which local account the leaf connection binds to,
	// which for a one-account edge is the org account.
	fmt.Fprintf(&b, "leafnodes {\n  remotes: [\n    { url: %q, account: %q, credentials: %q }\n  ]\n}\n\n",
		p.HubLeafURL, p.AccountPub, p.CredsFile)

	b.WriteString("# Local monitoring only (no $SYS user); keep bound to localhost.\n")
	b.WriteString("http: \"127.0.0.1:8222\"\n\n")

	// The agent reads this file to send a separately supervised leaf SIGHUP after
	// rewriting resolver_preload; an embedded leaf is reloaded in-process and
	// writes the agent's own pid here, which nothing reads.
	b.WriteString("# Lets the agent signal a separately supervised leaf to reload.\n")
	fmt.Fprintf(&b, "pid_file: %q\n", p.PidFile)
	return b.String()
}
